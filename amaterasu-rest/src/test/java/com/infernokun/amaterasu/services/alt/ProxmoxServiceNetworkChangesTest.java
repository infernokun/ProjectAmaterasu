package com.infernokun.amaterasu.services.alt;

import com.infernokun.amaterasu.models.LabActionResult;
import com.infernokun.amaterasu.models.entities.lab.LabTracker;
import com.infernokun.amaterasu.models.entities.lab.RemoteServer;
import com.infernokun.amaterasu.models.enums.ServerType;
import com.infernokun.amaterasu.utils.AESUtil;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.http.HttpMethod;
import org.springframework.http.MediaType;
import org.springframework.test.web.client.MockRestServiceServer;
import org.springframework.web.client.RestTemplate;

import java.util.ArrayList;
import java.util.List;

import static com.infernokun.amaterasu.services.alt.ProxmoxFixtures.addedBridge;
import static com.infernokun.amaterasu.services.alt.ProxmoxFixtures.changedVmbr0Address;
import static com.infernokun.amaterasu.services.alt.ProxmoxFixtures.diff;
import static com.infernokun.amaterasu.services.alt.ProxmoxFixtures.network;
import static com.infernokun.amaterasu.services.alt.ProxmoxFixtures.removedBridge;
import static com.infernokun.amaterasu.services.alt.ProxmoxService.UNKNOWN_INTERFACE;
import static com.infernokun.amaterasu.services.alt.ProxmoxService.touchedInterfaces;
import static com.infernokun.amaterasu.services.alt.ProxmoxServiceTeardownTest.NODE;
import static org.assertj.core.api.Assertions.assertThat;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;
import static org.springframework.test.web.client.match.MockRestRequestMatchers.method;
import static org.springframework.test.web.client.match.MockRestRequestMatchers.requestTo;
import static org.springframework.test.web.client.response.MockRestResponseCreators.withSuccess;

/** Deploy and teardown never reload a node's network while someone else's edits are pending there. */
class ProxmoxServiceNetworkChangesTest {
    private static final String PENDING = "Proxmox has unapplied network changes on proxmox2";

    private MockRestServiceServer node;
    private ProxmoxService proxmox;
    private RemoteServer server;
    private LabTracker tracker;

    @BeforeEach
    void setUp() {
        RestTemplate restTemplate = new RestTemplate();
        node = MockRestServiceServer.bindTo(restTemplate).build();
        AESUtil aes = mock(AESUtil.class);
        when(aes.decrypt("encrypted")).thenReturn("amaterasu@pve!labs=secret");
        proxmox = new ProxmoxService(aes, restTemplate);
        server = RemoteServer.builder().name("pve-a").ipAddress("10.0.0.205").nodeName("proxmox2")
                .serverType(ServerType.PROXMOX).apiToken("encrypted").build();
        server.setId("server-1");
        tracker = ProxmoxServiceTeardownTest.tracker(server);
    }

    @Test
    void readsWhichInterfacesAPendingDiffTouches() {
        assertThat(touchedInterfaces(null)).isEmpty();
        assertThat(touchedInterfaces("")).isEmpty();
        assertThat(touchedInterfaces(diff(addedBridge("abr3")))).containsExactly("abr3");
        assertThat(touchedInterfaces(diff(removedBridge("abr0"), addedBridge("abr1")))).containsExactly("abr0", "abr1");
        assertThat(touchedInterfaces(diff(changedVmbr0Address()))).containsExactly("vmbr0");
        assertThat(touchedInterfaces(diff(addedBridge("abr3"), changedVmbr0Address()))).containsExactly("abr3", "vmbr0");
        // A changed option whose iface line is outside the hunk's context
        assertThat(touchedInterfaces(diff("@@ -12,4 +12,5 @@", " \tgateway 10.0.0.1", " \tbridge-ports nic0",
                "+\tbridge-vlan-aware yes", " \tbridge-stp off"))).containsExactly(UNKNOWN_INTERFACE);
        assertThat(touchedInterfaces(diff("@@ -0,0 +1,2 @@", "+source /etc/network/interfaces.d/*"))).containsExactly(UNKNOWN_INTERFACE);
        // PVE's file header comment changes nothing
        assertThat(touchedInterfaces(diff("@@ -1,2 +1,3 @@", " # network interface settings; autogenerated",
                "+# Please do NOT modify this file directly", " "))).isEmpty();
        assertThat(touchedInterfaces("something PVE never sent")).containsExactly(UNKNOWN_INTERFACE);
    }

    @Test
    void realNodeNetworkWithoutPendingChangesHasNoChangesKey() {
        assertThat(ProxmoxFixtures.body("network.json")).doesNotContain("changes");
    }

    private void expectNetwork(String body) {
        node.expect(requestTo(NODE + "/network")).andExpect(method(HttpMethod.GET))
                .andRespond(withSuccess(body, MediaType.APPLICATION_JSON));
    }

    private void expectTemplate() {
        node.expect(requestTo(NODE + "/qemu")).andExpect(method(HttpMethod.GET)).andRespond(withSuccess(
                "{\"data\":[{\"vmid\":9000,\"name\":\"pivot-kali\",\"template\":1,\"status\":\"stopped\"}]}", MediaType.APPLICATION_JSON));
        node.expect(requestTo(NODE + "/qemu/9000/config")).andRespond(withSuccess(
                "{\"data\":{\"name\":\"pivot-kali\",\"net0\":\"virtio=52:54:00:aa:bb:cc,bridge=vmbr0,firewall=1\"}}", MediaType.APPLICATION_JSON));
    }

    @Test
    void deployCreatesNothingWhileOtherEditsArePending() {
        tracker.setVms(new ArrayList<>());
        tracker.setBridges(new ArrayList<>());
        expectTemplate();
        expectNetwork(network(diff(changedVmbr0Address())));

        LabActionResult result = proxmox.deployProxmoxLab(tracker, server);

        node.verify();
        assertThat(result.isSuccessful()).isFalse();
        assertThat(result.getOutput()).contains(PENDING + " (vmbr0); apply or revert them in the Proxmox UI first");
        assertThat(tracker.getBridges()).isEmpty();
    }

    @Test
    void deployTakesItsBridgeBackWhenOtherEditsAppearBeforeTheReload() {
        tracker.setVms(new ArrayList<>());
        tracker.setBridges(new ArrayList<>());
        expectTemplate();
        expectNetwork(network(null));
        node.expect(requestTo(NODE + "/network")).andExpect(method(HttpMethod.POST))
                .andRespond(withSuccess("{\"data\":null}", MediaType.APPLICATION_JSON));
        expectNetwork(network(diff(addedBridge("abr0"), changedVmbr0Address()), "abr0"));
        node.expect(requestTo(NODE + "/network/abr0")).andExpect(method(HttpMethod.DELETE))
                .andRespond(withSuccess("{\"data\":null}", MediaType.APPLICATION_JSON));

        LabActionResult result = proxmox.deployProxmoxLab(tracker, server);

        node.verify();
        assertThat(result.isSuccessful()).isFalse();
        assertThat(result.getOutput()).contains(PENDING + " (vmbr0)").doesNotContain("Apply network changes");
        assertThat(tracker.getBridges()).isEmpty();
    }

    @Test
    void teardownLeavesBridgesAndDoesNotReloadWhileOtherEditsArePending() {
        tracker.setVms(new ArrayList<>());
        expectNetwork(network(diff(changedVmbr0Address()), "abr0"));

        LabActionResult result = proxmox.teardownProxmoxLab(tracker, server);

        node.verify();
        assertThat(result.isSuccessful()).isFalse();
        assertThat(result.getOutput()).contains(PENDING);
        assertThat(tracker.getBridges()).containsExactly("abr0");
    }

    @Test
    void teardownStopsBeforeTheReloadWhenOtherEditsAppearAfterItsRemovals() {
        tracker.setVms(new ArrayList<>());
        expectNetwork(network(null, "abr0"));
        node.expect(requestTo(NODE + "/network/abr0")).andExpect(method(HttpMethod.DELETE))
                .andRespond(withSuccess("{\"data\":null}", MediaType.APPLICATION_JSON));
        expectNetwork(network(diff("@@ -1,1 +1,1 @@", "-source /etc/network/interfaces.d/*", "+source-directory /etc/net"), "abr0"));

        LabActionResult result = proxmox.teardownProxmoxLab(tracker, server);

        node.verify();
        assertThat(result.isSuccessful()).isFalse();
        assertThat(result.getOutput()).contains(PENDING + "; apply or revert them in the Proxmox UI first");
        assertThat(tracker.getBridges()).containsExactly("abr0");
    }

    @Test
    void teardownAppliesItsOwnPendingRemovalFromAnEarlierAttempt() {
        tracker.setVms(new ArrayList<>());
        // abr0 is already gone from interfaces.new but still up on the node
        expectNetwork(network(diff(removedBridge("abr0"))));
        expectNetwork(network(diff(removedBridge("abr0"))));
        ProxmoxServiceTeardownTest.expectReload(node);

        LabActionResult result = proxmox.teardownProxmoxLab(tracker, server);

        node.verify();
        assertThat(result.isSuccessful()).isTrue();
        assertThat(tracker.getBridges()).isEmpty();
    }

    @Test
    void teardownWithNothingOfItsOwnLeftDoesNotReloadOtherEdits() {
        tracker.setVms(new ArrayList<>());
        tracker.setBridges(new ArrayList<>(List.of("abr0")));
        expectNetwork(network(diff(changedVmbr0Address())));

        LabActionResult result = proxmox.teardownProxmoxLab(tracker, server);

        node.verify();
        assertThat(result.isSuccessful()).isTrue();
        assertThat(tracker.getBridges()).isEmpty();
    }
}
